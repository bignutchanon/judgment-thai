# สแกนหาที่ยังเหลือ — แบบที่ตั้งใจ (EN ซ้ำเอง / เสียงหัวเราะ) ไม่อยู่ในรายการนี้
CHECK_RE = re.compile(
    r"ตี(?:หก|เจ็ด|แปด|เก้า|สิบ)"
    # ที่ที่ · เจ้าหน้าที่ที่ · สถานที่ที่ — เว้น เต็มที่ที่สุด / (น่าเสียดาย)ที่ที่นั่น / ที่ที่นี่
    r"|(?<![ก-๛])ที่ที่|[ก-๛]ที่ที่(?!สุด|นี่|นั่น)"
    r"|คนคน(?!ละ)|ขอบคุณคุณ|บุญคุณคุณ|นี่นี่(?!เอง)|มันมัน|มีมี(?!ด)|ให้ให้|ของของ|กับกับ|มือมือ"
    r"|ใช่ใช่|จริงจริง|บันทึกบันทึก|ภาพภาพ|สิบสิบ|(?:โนะ|เนะ|ชนะ)นะ(?![ก-๛])"
)


def apply_rules(s, hits):
    for i, (old, new) in enumerate(RULES):
        if old in s:
            hits[i] += s.count(old)
            s = s.replace(old, new)
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true", help="สแกน master_th หาที่ยังเหลือ")
    a = ap.parse_args()

    if a.check:
        master = json.load(io.open(paths.MASTER_TH, encoding="utf-8"))
        n = 0
        for en, th in master.items():
            m = CHECK_RE.search(th)
            if m:
                n += 1
                print("[%s] %s" % (m.group(0), th.replace("\n", " | ")[:120]))
        print("เหลือ %d บรรทัด" % n)
        return 1 if n else 0

    hits = [0] * len(RULES)
    changed = 0
    for p in sorted(DONE.glob("*.done.json")):
        d = json.load(io.open(p, encoding="utf-8"))
        dirty = False
        for en, th in d["strings"].items():
            new = apply_rules(th, hits)
            if new != th:
                changed += 1
                dirty = True
                d["strings"][en] = new
                if not a.write:
                    print("%s\n  - %s\n  + %s" % (p.name, th.replace("\n", " | "), new.replace("\n", " | ")))
        if dirty and a.write:
            io.open(p, "w", encoding="utf-8", newline="\n").write(
                json.dumps(d, ensure_ascii=False, indent=1))
    unused = [RULES[i][0] for i, h in enumerate(hits) if not h]
    for u in unused:
        print("กฎไม่เจอเลย: %r" % u)
    print("แก้ %d ข้อความ%s" % (changed, " (เขียนแล้ว — รัน remerge_stale.py --write ต่อ)" if a.write
                                  else " (ใส่ --write เพื่อแก้)"))
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
