#!/usr/bin/env python3
"""ตาราง advance/kerning ของ `meta_ot_cond_book` — ที่อยู่จริง สูตร และตัวช่วยคำนวณ

## ค้นพบ 22 ส.ค. 2026 (รอบ 16) — ตาราง width ไม่ได้อยู่ใน exe

ก่อนหน้านี้ทั้งโปรเจกต์เชื่อว่า advance ของแต่ละเซลล์ถูก hardcode ไว้ใน `Judgment.exe`
(สแกนไฟล์ 394 MB และ RAM 5.6 GB แล้วไม่เจอ) ความจริงคือมันอยู่ในไฟล์ข้อมูลที่เราแก้ได้มาตลอด:

    data/db.judge.en.par
      └── en/font.bin                     (ARMP v2 · 25 แถว = ฟอนต์ในเกม)
            └── แถว "meta_ot_cond_book"
                  └── คอลัมน์ `kerning_table`   (ARMP ซ้อนอีกชั้น)
                        332 แถว x 6 คอลัมน์ float

หลักฐาน: ม็อดไทยเก่า MOD2SUB แก้ไฟล์นี้ (71 แถว ช่วง cell 0x81-0x14B ตรงกับ donor ของเราเป๊ะ)
และภาพในเกมของเขามีสระ/วรรณยุกต์ซ้อนบนฐานจริง ทั้งที่ atlas ของเขา **ไม่มี pre-compose เลย**
(ถอดสตริงจาก par ของเขาแล้ว: "เอาชนะพวกอันธพาล" = 16 codepoint ต่อ 16 ตัวอักษร)

## สูตร (fit กับข้อมูลจริง 171 จุดจาก probe หวีของเราเอง: ค่าคลาดเคลื่อนเฉลี่ย 0.27 px)

    advance  = CELL_ADV - K * (L + R)          # L = คอลัมน์คู่ซ้าย, R = คอลัมน์คู่ขวา
    x_offset = -K * L                          # กลิฟถูกเลื่อน "ซ้าย" จากตำแหน่งปากกา

โดย `K = 18.0` และ `CELL_ADV = 36.0` พอดี → ค่าที่เก็บคือหน่วย em ที่ครึ่ง em = 1.0
(เซลล์เต็ม = 2.0) ดังนั้น `L + R = 2.0` หมายถึง advance = 0 พอดี และเกิน 2.0 ได้ = advance ติดลบ

6 คอลัมน์ = 3 คู่ (L,R) สำหรับ "ขนาดวาด" 3 แบบของเอนจิ้น:
    คู่ (1,2) · คู่ (3,4) · คู่ (5,6)
เมนูไตเติล/probe ของเราใช้คู่ (5,6) · แถบภารกิจในภาพของ MOD2SUB ใช้คู่ (3,4)
→ **เขียนค่าเดียวกันลงทั้งสามคู่เสมอ** ทุกชั้นจะได้ระยะเท่ากันหมด (MOD2SUB ก็ทำแบบนี้)

## ผลที่ตามมา (เหตุผลที่สถาปัตยกรรมฟอนต์ของโปรเจกต์เปลี่ยนทั้งชุดในรอบ 16)

* มาร์ก (สระบน/ล่าง/วรรณยุกต์) ตั้ง advance = 0 ได้ → **เลิก pre-compose ฐาน+มาร์ก**
  หนึ่งตัวอักษรไทย = หนึ่งเซลล์ ตรงไปตรงมา
* ฐานตั้ง advance = ความกว้าง ink จริง + side bearing → เพดาน 36 px หายไป ตัวอักษรชิดปกติ
* ตารางมี **332 แถว** = cell 0..331 = ถึง U+016B เท่านั้น → นี่คือสาเหตุที่ Latin Ext-B
  (U+0180-019F) ขึ้นเป็นกล่องเปล่า ไม่ใช่เพราะ atlas
"""

K = 18.0                 # px ต่อ 1.0 หน่วยในตาราง (ครึ่ง em)
CELL_ADV = 36.0          # advance เมื่อ L = R = 0 (= 2.0 หน่วย)
KERN_ROWS = 332          # จำนวนแถวในตาราง = เพดาน cell index ที่เอนจิ้นวาดได้
LAST_CELL = KERN_ROWS - 1

LSB = 1                  # ช่องไฟซ้ายของกลิฟฐาน (px) — เท่ากับฟอนต์อังกฤษเดิม
RSB = 3                  # ช่องไฟขวาของกลิฟฐาน (px) — เท่ากับฟอนต์อังกฤษเดิม (วัดจาก M/a/b/c)


def cell_index(cp):
    """codepoint -> เลขเซลล์ในตาราง (= เลขแถวของ kerning_table)"""
    return cp if cp < 0x80 else cp - 0x20


def in_table(cp):
    return cell_index(cp) <= LAST_CELL


def lr_for(advance, ink_x0, place):
    """คืน (L, R) ที่ทำให้เซลล์นี้มี advance ตามต้องการ และ ink ตกลงตำแหน่งที่ต้องการ

    ink_x0 = ตำแหน่ง x ของขอบซ้าย ink ในเซลล์ (px ที่เราวาดเอง)
    place  = ตำแหน่งที่อยากให้ขอบซ้าย ink ไปตกบนจอ วัดจากปากกา (ลบ = ซ้ายของปากกา)
    """
    offset = ink_x0 - place                  # ต้องเลื่อนกลิฟไปซ้ายเท่านี้
    L = offset / K
    R = (CELL_ADV - advance) / K - L
    return L, R


def base_advance(ink_w):
    """advance ของกลิฟฐาน = ความกว้าง ink + side bearing สองข้าง"""
    return ink_w + LSB + RSB


def mark_place(base_ink_w, mark_ink_w):
    """ขอบซ้ายของมาร์กควรไปตกที่ไหน (วัดจากปากกา) เพื่อให้อยู่กึ่งกลางฐานตัวก่อนหน้า

    ปากกาอยู่ที่ base_pen + base_advance(base_ink_w) แล้ว จึงต้องถอยกลับมา
    """
    return -(base_ink_w / 2.0 + mark_ink_w / 2.0 + RSB)
